import { spawn } from 'node:child_process';
import { createHash } from 'node:crypto';
import { existsSync } from 'node:fs';
import { cp, mkdir, readFile, readdir, rm, stat, writeFile } from 'node:fs/promises';
import * as path from 'node:path';
import * as vscode from 'vscode';
import { PlanLog } from './log';
import { EVAL_FILE, EvalValue, OVERRIDE_FILE, batchFile, consoleQuery, errorsByIndex, parseConsole } from './model/evalBatch';
import { Env, lastErrorLine } from './model/envs';
import { localModuleDirs } from './model/roots';

const SKIP = new Set(['.terraform', '.git', 'node_modules', '.terragrunt-cache']);
const MAX_FILE = 1024 * 1024;
/** Terraform asks for an init (new module, provider or lock file entry). */
const NEEDS_INIT = /terraform init|Module not installed|Missing required provider|Inconsistent dependency lock file|Backend initialization required|Required plugins are not installed|module.*not.*installed/i;

interface Run {
  code: number;
  stdout: string;
  stderr: string;
}

/**
 * Evaluates expressions with terraform console, for the inline values. Never on the real state: the env's root and the
 * local modules it calls are mirrored into the extension's storage with a local backend (console locks the state it
 * reads). See docs/design/2026-10-30-inline-values-design.md.
 */
export class Evaluator {
  /** Mirrors initialised in this session (by mirror folder). */
  private readonly inited = new Set<string>();
  private readonly workspaces = new Set<string>();

  constructor(
    private readonly out: PlanLog,
    private readonly globalStorage: string,
    private readonly tfPath: () => string,
  ) {}

  /**
   * Values of the expressions (root module scope of env.root), in order. overlays: unsaved editor text by absolute
   * path, used over the file on disk.
   */
  async evaluate(env: Env, exprs: string[], overlays: Map<string, string>): Promise<EvalValue[]> {
    if (!vscode.workspace.isTrusted) throw new Error('Workspace not trusted: values need terraform, which runs code from the workspace.');
    const hash = createHash('sha1').update(env.root).digest('hex').slice(0, 12);
    const base = path.join(this.globalStorage, 'eval', hash);
    const data = path.join(this.globalStorage, 'eval-data', hash);
    const root = await this.mirror(env.root, path.join(base, 'src'), overlays);
    await mkdir(data, { recursive: true });
    await writeFile(path.join(root, OVERRIDE_FILE), [
      '# Generated by Plan Lens: its own local state, so terraform console never locks the real one.',
      'terraform {',
      `  backend "local" {`,
      `    path          = ${JSON.stringify(path.join(data, 'eval.tfstate'))}`,
      `    workspace_dir = ${JSON.stringify(path.join(data, 'workspaces'))}`,
      '  }',
      '}',
      '',
    ].join('\n'));
    const vars: NodeJS.ProcessEnv = {
      TF_DATA_DIR: path.join(data, 'tfdata'),
      TF_PLUGIN_CACHE_DIR: process.env.TF_PLUGIN_CACHE_DIR || path.join(this.globalStorage, 'plugin-cache'),
    };
    await mkdir(vars.TF_PLUGIN_CACHE_DIR!, { recursive: true });
    if (!this.inited.has(root) || !existsSync(vars.TF_DATA_DIR!)) await this.init(root, vars);
    if (env.workspace && !this.workspaces.has(`${root}|${env.workspace}`)) {
      // The workspace exists in the local eval state so terraform.workspace reads like in a real run.
      await this.run(root, ['workspace', 'new', env.workspace], vars);
      this.workspaces.add(`${root}|${env.workspace}`);
    }
    if (env.workspace) vars.TF_WORKSPACE = env.workspace;
    const varFile = env.tfvars ? [`-var-file=${env.tfvars}`] : [];

    const values: EvalValue[] = exprs.map(() => ({ kind: 'error', message: 'not evaluated' }));
    let active = exprs.map((_, i) => i);
    // Each round drops the expressions terraform names as broken, until the rest evaluates.
    for (let round = 0; round < 6 && active.length; round++) {
      const { text, starts } = batchFile(active.map((i) => exprs[i]));
      await writeFile(path.join(root, EVAL_FILE), text);
      let r = await this.run(root, ['console', ...varFile], vars, consoleQuery(active.map((_, k) => k)));
      if (r.code !== 0 && NEEDS_INIT.test(r.stderr)) {
        await this.init(root, vars);
        r = await this.run(root, ['console', ...varFile], vars, consoleQuery(active.map((_, k) => k)));
      }
      // terraform console reports a broken expression and still exits 0, its value then unknown: errors first.
      const broken = errorsByIndex(r.stderr, starts);
      if (broken.size) {
        for (const [k, message] of broken) values[active[k]] = { kind: 'error', message };
        active = active.filter((_, k) => !broken.has(k));
        continue;
      }
      if (r.code === 0) {
        const got = parseConsole(r.stdout);
        const caught: number[] = [];
        active.forEach((i, k) => {
          const v = got.get(k) ?? { kind: 'error', message: 'no value' };
          values[i] = v;
          if (v.kind === 'error' && !v.message) caught.push(i);
        });
        if (caught.length) await this.explain(root, vars, varFile, exprs, caught, values);
        return values;
      }
      // Not one of the expressions: the configuration itself does not load (a syntax error, a bad tfvars…).
      const message = lastErrorLine(r.stderr) || `terraform console failed (${r.code})`;
      for (const i of active) values[i] = { kind: 'error', message };
      return values;
    }
    return values;
  }

  /** Why the caught (try) failures fail: the same expressions without try, so terraform names each one. */
  private async explain(root: string, vars: NodeJS.ProcessEnv, varFile: string[], exprs: string[], idx: number[], values: EvalValue[]): Promise<void> {
    const { text, starts } = batchFile(idx.map((i) => exprs[i]), true);
    await writeFile(path.join(root, EVAL_FILE), text);
    const r = await this.run(root, ['console', ...varFile], vars, consoleQuery(idx.map((_, k) => k)));
    const why = errorsByIndex(r.stderr, starts);
    idx.forEach((i, k) => (values[i] = { kind: 'error', message: why.get(k) ?? 'evaluation error' }));
  }

  private async init(root: string, vars: NodeJS.ProcessEnv): Promise<void> {
    this.out.heading(`── Values: terraform init in Plan Lens's own copy · ${new Date().toLocaleTimeString()} ──`);
    const r = await this.run(root, ['init', '-input=false', '-reconfigure'], vars, undefined, true);
    if (r.code !== 0) throw new Error(lastErrorLine(r.stderr) || 'terraform init failed');
    this.inited.add(root);
  }

  /**
   * Copies the root and the local modules it calls (recursively) under `dest`, keeping their relative layout, so
   * `source = "../modules/x"` still resolves. Returns the root's folder in the copy.
   */
  private async mirror(root: string, dest: string, overlays: Map<string, string>): Promise<string> {
    const dirs = new Set<string>([root]);
    const queue = [root];
    while (queue.length) {
      const dir = queue.pop()!;
      for (const f of await readdir(dir).catch(() => [] as string[])) {
        if (!f.endsWith('.tf')) continue;
        const file = path.join(dir, f);
        const text = overlays.get(file) ?? (await readFile(file, 'utf8').catch(() => ''));
        for (const m of localModuleDirs(dir, text)) {
          if (!dirs.has(m) && existsSync(m)) {
            dirs.add(m);
            queue.push(m);
          }
        }
      }
    }
    const top = commonDir([...dirs]);
    await rm(dest, { recursive: true, force: true });
    for (const dir of dirs) {
      await cp(dir, path.join(dest, path.relative(top, dir)), {
        recursive: true,
        filter: async (src) => {
          const name = path.basename(src);
          if (SKIP.has(name) || /^terraform\.tfstate/.test(name)) return false;
          const st = await stat(src).catch(() => undefined);
          return !!st && (st.isDirectory() || st.size <= MAX_FILE);
        },
      });
    }
    for (const [file, text] of overlays) {
      const dir = [...dirs].find((d) => path.dirname(file) === d);
      if (dir) await writeFile(path.join(dest, path.relative(top, file)), text);
    }
    return path.join(dest, path.relative(top, root));
  }

  private run(cwd: string, args: string[], vars: NodeJS.ProcessEnv, stdin?: string, log = false): Promise<Run> {
    if (log) this.out.command(`${path.basename(this.tfPath())} ${args.join(' ')}`);
    return new Promise((resolve) => {
      const env: NodeJS.ProcessEnv = { ...process.env, TF_IN_AUTOMATION: '1', TF_CLI_ARGS: '', TF_WORKSPACE: undefined, ...vars };
      const child = spawn(this.tfPath(), args, { cwd, env, shell: false });
      let stdout = '';
      let stderr = '';
      child.stdout.setEncoding('utf8');
      child.stderr.setEncoding('utf8');
      child.stdout.on('data', (s: string) => (stdout += s));
      child.stderr.on('data', (s: string) => {
        stderr += s;
        if (log) this.out.append(s);
      });
      child.on('error', (e) => resolve({ code: -1, stdout, stderr: `Error: could not start ${this.tfPath()} (${e.message})` }));
      child.on('close', (code) => resolve({ code: code ?? -1, stdout, stderr }));
      child.stdin.end(stdin ? `${stdin}\n` : '');
    });
  }
}

function commonDir(dirs: string[]): string {
  let top = dirs[0];
  for (const d of dirs) while (path.relative(top, d).startsWith('..')) top = path.dirname(top);
  return top;
}
